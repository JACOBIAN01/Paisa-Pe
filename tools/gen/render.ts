import layersJson from './layers.json';
import type { Layer, PackageSpec } from './registry';

const SINGLETON_LAYERS: Layer[] = ['design-system', 'harness', 'tools'];
const FLAT_SOURCE_LAYERS: Layer[] = ['harness', 'tools'];

const NAME_PREFIX: Record<Layer, string> = {
  contracts: 'contracts-',
  core: 'core-',
  platform: 'platform-',
  mockplatform: 'mock-',
  services: 'svc-',
  features: 'feat-',
  'design-system': '',
  apps: 'app-',
  harness: '',
  tools: '',
};

const LAYER_LABEL: Record<Layer, string> = {
  contracts: 'L0 contracts',
  core: 'L1 core',
  platform: 'L2 platform',
  services: 'L3 services',
  features: 'L4 features',
  apps: 'L5 apps',
  mockplatform: 'side: mockplatform',
  'design-system': 'side: design-system',
  harness: 'side: harness',
  tools: 'side: tools',
};

export const FEATURE_DIRS = ['screens', 'components', 'hooks', 'state'];

export const isSingleton = (s: PackageSpec): boolean => SINGLETON_LAYERS.includes(s.layer);
export const packagePath = (s: PackageSpec): string =>
  isSingleton(s) ? s.layer : `${s.layer}/${s.slug}`;
export const packageName = (s: PackageSpec): string => `@pp/${NAME_PREFIX[s.layer]}${s.slug}`;
export const entryPath = (s: PackageSpec): string =>
  FLAT_SOURCE_LAYERS.includes(s.layer) ? 'index.ts' : 'src/index.ts';

const json = (value: unknown): string => `${JSON.stringify(value, null, 2)}\n`;

export function renderPackageJson(s: PackageSpec): string {
  return json({
    name: packageName(s),
    version: '0.0.0',
    private: true,
    description: s.description,
    main: entryPath(s),
    types: entryPath(s),
    scripts: { typecheck: 'tsc --noEmit -p tsconfig.json' },
    ...(s.deps ? { dependencies: s.deps } : {}),
  });
}

export function renderTsconfig(s: PackageSpec): string {
  const depth = packagePath(s).split('/').length;
  const include = FLAT_SOURCE_LAYERS.includes(s.layer)
    ? ['.']
    : s.layer === 'apps'
      ? ['src', 'app']
      : ['src'];
  return json({
    extends: `${'../'.repeat(depth)}tsconfig.base.json`,
    include,
    exclude: ['node_modules'],
  });
}

export function allowedLayers(s: PackageSpec): string[] {
  return layersJson.layers[s.layer];
}

export function forbiddenLayers(s: PackageSpec): string[] {
  const allowed = new Set(allowedLayers(s));
  return (Object.keys(layersJson.layers) as Layer[]).filter((l) => !allowed.has(l));
}

const bullets = (items: string[]): string => items.map((i) => `- ${i}`).join('\n');

export function renderReadme(s: PackageSpec): string {
  return `# ${packageName(s)}

${s.description}

**Layer:** ${LAYER_LABEL[s.layer]}
**Owner:** ${s.team}

## Owns

${bullets(s.owns)}

## Public API

Everything other packages may use is exported from \`${entryPath(s)}\`. Deep imports are not allowed.
`;
}

export function renderClaudeMd(s: PackageSpec): string {
  const allowed = allowedLayers(s);
  const own = (layersJson.ownPackageOnly as string[]).includes(s.layer);
  const forbidden = forbiddenLayers(s);
  return `# ${packageName(s)}

Owner: ${s.team}. Layer: ${LAYER_LABEL[s.layer]}.

## Owns

${bullets(s.owns)}

## May import

${bullets(allowed.map((l) => `\`${l}/*\` (through its public entry point)`))}
${own ? '\nWithin `features/*` this package may only import itself; no feature-to-feature imports.\n' : ''}
## Must not import

${bullets(forbidden.length > 0 ? forbidden.map((l) => `\`${l}/*\``) : ['(nothing outside the allowed list)'])}

## Rules

- Public API is \`${entryPath(s)}\` only. Import other packages by their \`@pp/*\` name, never by relative path or deep path.
- Layer rules are enforced by \`pnpm lint\` and \`pnpm cycles\`.
- Keep files small and focused. Add tests next to the code they cover.
`;
}

export function renderCodeowners(specs: PackageSpec[]): string {
  const lines = specs.map((s) => {
    const path = `/${packagePath(s)}/`;
    return `${path.padEnd(36)}@paisape/${s.team}`;
  });
  return `# Generated by tools/gen. Do not edit by hand.\n* @paisape/platform-core\n${lines.join('\n')}\n`;
}

export function renderPaths(specs: PackageSpec[]): Record<string, string[]> {
  const entries = specs.map((s): [string, string[]] => [
    packageName(s),
    [`${packagePath(s)}/${entryPath(s)}`],
  ]);
  return Object.fromEntries(entries.sort(([a], [b]) => a.localeCompare(b)));
}
